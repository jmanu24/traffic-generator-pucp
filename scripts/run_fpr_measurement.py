"""PILOT2 blocker (2026-10-24): run C1-I (benign-only, isolated detection
mode, pipeline enabled) for the 15 fresh seeds (301-315) generated by
generate_fpr_benign_plans.py, to measure the SYN_FLOOD single-source
detector's intrinsic false-positive rate under real benign traffic
alone -- the mechanism found behind composition3_f09's one I-coverage
violation (seed 206: detection fired 12s AFTER the attack window ended,
from ent-site-3's own benign SYN rate alone). Same /api/runs pattern as
run_pilot2.py; exports+checks each run immediately so this is a single
pass, no separate pull step needed."""
import io
import json
import sys
import time
import urllib.error
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path('/home/ubuntu/traffic-generator-pucp')
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'scripts'))
from run_pilot import load_token, call, wait_for_completion

BASE = 'http://192.168.18.154:8780'
MANIFEST_PATH = ROOT / 'data' / 'fpr_benign_plans_manifest.json'
OUT_PATH = Path('/home/ubuntu/isp-ddos-ryu/.runtime/benign-lab/calibration/fpr_measurement.json')
CACHE = Path('/home/ubuntu/isp-ddos-ryu/.runtime/benign-lab/calibration/fpr_exports')
PAUSE_S = 30


def export_and_check(token, rid):
    req = urllib.request.Request(f'{BASE}/api/runs/{rid}/export', method='GET',
                                  headers={'Authorization': 'Bearer ' + token})
    with urllib.request.urlopen(req, timeout=120) as resp:
        raw = resp.read()
    outdir = CACHE / rid
    outdir.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        if 'detection_events.jsonl' in z.namelist():
            (outdir / 'detection_events.jsonl').write_bytes(z.read('detection_events.jsonl'))
        if 'run.json' in z.namelist():
            (outdir / 'run.json').write_bytes(z.read('run.json'))
    lines = (outdir / 'detection_events.jsonl').read_text().splitlines() if (outdir / 'detection_events.jsonl').exists() else []
    detections = [json.loads(l) for l in lines if l.strip() and json.loads(l).get('kind') == 'detection']
    return detections


def main():
    token = load_token()
    manifest = json.loads(MANIFEST_PATH.read_text())
    results = json.loads(OUT_PATH.read_text()) if OUT_PATH.exists() else []
    done_seeds = {r['seed'] for r in results}

    for i, entry in enumerate(manifest):
        seed = entry['seed']
        if seed in done_seeds:
            print(f'[{i+1}/{len(manifest)}] seed={seed} already done, skipping', flush=True)
            continue
        body = dict(mode='lab', scenario='B0', pipeline='enabled', speed=1,
                    plan_hash=entry['plan_hash'], detection_mode='I')
        result = call(token, 'POST', '/api/runs', body)
        if result.get('error'):
            print(f'[{i+1}/{len(manifest)}] seed={seed} start_error:', result, flush=True)
            results.append(dict(seed=seed, plan_hash=entry['plan_hash'], start_error=result))
            OUT_PATH.write_text(json.dumps(results, indent=2))
            continue
        rid = result['id']
        final = wait_for_completion(token, rid)
        detections = export_and_check(token, rid)
        n_fp = len(detections)
        print(f'[{i+1}/{len(manifest)}] seed={seed} run_id={rid} status={final["status"]} detections={n_fp}', flush=True)
        if n_fp:
            for d in detections:
                print('   FP:', d.get('detection', {}).get('src_ip'), d.get('detection', {}).get('domain'),
                      d.get('detection', {}).get('pps'), 'timestamp=', d.get('timestamp'), flush=True)
        results.append(dict(seed=seed, plan_hash=entry['plan_hash'], run_id=rid, status=final['status'],
                             n_detections=n_fp, detections=detections))
        OUT_PATH.write_text(json.dumps(results, indent=2))
        if i < len(manifest) - 1:
            time.sleep(PAUSE_S)

    n = len(results)
    n_fp_runs = sum(1 for r in results if r.get('n_detections', 0) > 0)
    print(f'\nDone. {n_fp_runs}/{n} runs had >=1 spurious detection.', flush=True)


if __name__ == '__main__':
    main()
